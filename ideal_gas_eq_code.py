# ===================================================
# 이상기체 상태방정식: PV = nRT
# P: 압력 (Pa)
# V: 부피 (m^3)
# n: 몰수 (mol)
# R: 기체상수 (J/(mol*K))
# T: 온도 (K)
# ===================================================

# 기체상수 R을 정의해줘 (단위: J/(mol*K))
# 이 값은 항상 고정된 상수이기 때문에 대문자로 표기하는 게 관례야
R = 8.314  # J/(mol*K)

# -----------------------------
# 사용자로부터 입력값 받기
# -----------------------------
# input()으로 받은 값은 항상 "문자열(string)"이기 때문에
# float()으로 감싸서 실수(소수점 있는 숫자)로 변환해줘야 계산이 가능해
n = float(input("몰수 n (mol)을 입력하세요: "))
T = float(input("온도 T (K, 켈빈)를 입력하세요: "))
V = float(input("부피 V (m^3)를 입력하세요: "))

# -----------------------------
# 압력 P 계산하기
# -----------------------------
# PV = nRT 를 P에 대해 정리하면 -> P = nRT / V
P = (n * R * T) / V

# -----------------------------
# 결과 출력하기
# -----------------------------
# f-string(f"...") 문법을 쓰면 중괄호 {} 안에 변수를 바로 넣어서 출력할 수 있어
# :.2f 는 소수점 둘째 자리까지만 보여주라는 뜻이야 (formatting)
print(f"계산된 압력 P = {P:.2f} Pa")

# 참고로 1 atm = 101325 Pa 이니까, atm 단위로도 변환해서 보여줄게
P_atm = P / 101325
print(f"이를 atm 단위로 바꾸면 P = {P_atm:.4f} atm")